#!/usr/bin/env python3
"""Generate committed code from contracts/openapi.yaml (story M0-E01-S04; DR-012 D4 = A).

Outputs (both committed; `make openapi` fails when they differ from the generator's output):
  frontend/src/api/schema.ts          TypeScript types and the response schemas used for strict runtime decoding
  backend/internal/api/routes_gen.go  the declared routes the API handler uses to answer typed rejections

Supports only the OpenAPI subset tools/check_openapi.py allows (this is maintained code, refinement review N6).
Standard library plus the pinned PyYAML. Default mode only compares and writes nothing; use --write to update.
Exit codes: 0 up to date (or written), 1 drift, 2 usage or environment error.
"""
import argparse
import importlib.util
import json
import sys
from pathlib import Path

sys.dont_write_bytecode = True

ROOT = Path(__file__).resolve().parents[1]
TS_OUT = "frontend/src/api/schema.ts"
GO_OUT = "backend/internal/api/routes_gen.go"
HEADER = "Generated by tools/gen_api_types.py from contracts/openapi.yaml. DO NOT EDIT."
TS_NAMES = {"Error": "ApiError"}  # `Error` would shadow the global


def load_checker():
    spec = importlib.util.spec_from_file_location("check_openapi", ROOT / "tools" / "check_openapi.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def ts_name(name):
    return TS_NAMES.get(name, name)


def ts_literal(value):
    return json.dumps(value)


def ts_type(node, indent=0):
    """TypeScript type for a schema node."""
    if "$ref" in node:
        return ts_name(node["$ref"].rsplit("/", 1)[1])
    if "const" in node:
        return ts_literal(node["const"])
    types = node.get("type")
    types = types if isinstance(types, list) else [types]
    parts = []
    for t in types:
        if t == "string":
            parts.append(" | ".join(ts_literal(v) for v in node["enum"] if isinstance(v, str)) if "enum" in node else "string")
        elif t == "integer":
            parts.append("number")
        elif t == "boolean":
            parts.append("boolean")
        elif t == "null":
            parts.append("null")
        elif t == "array":
            if node.get("maxItems") == 0:
                parts.append("never[]")
            else:
                inner = ts_type(node["items"], indent)
                parts.append("(%s)[]" % inner if any(c in inner for c in "|{") else inner + "[]")
        elif t == "object":
            parts.append(ts_object(node, indent))
        else:
            raise ValueError("unsupported type %r" % (t,))
    return " | ".join(dict.fromkeys(parts))


def ts_object(node, indent):
    props = node.get("properties") or {}
    if not props:
        return "Record<string, never>"
    required = set(node.get("required") or [])
    pad = "  " * (indent + 1)
    lines = []
    for name, sub in props.items():
        lines.append("%s%s%s: %s;" % (pad, name, "" if name in required else "?", ts_type(sub, indent + 1)))
    return "{\n" + "\n".join(lines) + "\n" + "  " * indent + "}"


def render_ts(spec):
    schemas = spec["components"]["schemas"]
    errors = schemas["Error"]["properties"]["category"]["enum"]
    out = ["// %s" % HEADER,
           "// Types for the browser-api shapes (M0-E01-S04, DR-012 D4). `SCHEMAS` is the JSON form of the response and",
           "// request schemas, decoded strictly at runtime by ./validate.ts. Change contracts/openapi.yaml, not this file.",
           "",
           "export const API_VERSION = %s;" % ts_literal(spec["info"]["version"]),
           "export type ErrorCategory = %s;" % " | ".join(ts_literal(v) for v in errors),
           "export const ERROR_CATEGORIES: readonly ErrorCategory[] = %s;" % ts_literal(errors),
           ""]
    for name, node in schemas.items():
        if name == "Error":
            body = ts_object({"properties": {k: v for k, v in node["properties"].items()}, "required": node["required"]}, 0)
            out.append("export interface ApiError %s" % body)
        else:
            out.append("export interface %s %s" % (ts_name(name), ts_object(node, 0)))
        out.append("")
    out.append("export const SCHEMAS = %s as const;" % json.dumps({ts_name(n): s for n, s in schemas.items()}, indent=2, sort_keys=True))
    out.append("")
    out.append("export type SchemaName = keyof typeof SCHEMAS;")
    out.append("")
    routes = []
    for path, item in spec["paths"].items():
        for method, op in item.items():
            ok = next(st for st in op["responses"] if st.startswith("2"))
            schema_name = ts_name(op["responses"][ok]["content"]["application/json"]["schema"]["$ref"].rsplit("/", 1)[1])
            routes.append({"method": method.upper(), "path": path, "category": op["x-request-category"],
                           "implemented": op["x-implementation-status"] == "implemented",
                           "success": {"status": int(ok), "schema": schema_name},
                           "error_statuses": sorted(int(st) for st in op["responses"] if not st.startswith("2"))})
    out.append("/** Every declared route with its success schema and error statuses (error bodies are ApiError). */")
    out.append("export const ROUTES = %s as const;" % json.dumps(routes, indent=2))
    out.append("")
    return "\n".join(out)


def render_go(spec):
    co = load_checker()
    rows = []
    for path, item in spec["paths"].items():
        for method, op in item.items():
            rows.append((method.upper(), path, op["x-implementation-status"] == "implemented"))
    rows.sort(key=lambda r: (r[1], r[0]))
    for _, path, _ in rows:
        if "\"" in path or "`" in path or "\\" in path:
            raise ValueError("unsafe path")
    assert len(rows) == len(co.PATHS)
    out = ["// %s" % HEADER,
           "",
           "package api",
           "",
           "// declaredRoutes lists every method and path template contracts/openapi.yaml declares. Only routes",
           "// marked implemented are served; the others are rejected with a typed error (DR-012 D5).",
           "var declaredRoutes = []declaredRoute{"]
    for method, path, implemented in rows:
        out.append('\t{method: "%s", template: "%s", implemented: %s},' % (method, path, "true" if implemented else "false"))
    out.append("}")
    out.append("")
    return "\n".join(out)


def outputs(root):
    co = load_checker()
    spec = co.load_yaml((Path(root) / co.SPEC_FILE).read_bytes())
    return {TS_OUT: render_ts(spec), GO_OUT: render_go(spec)}


def main(argv=None):
    parser = argparse.ArgumentParser(description="Generate or check the committed API types and route table.")
    parser.add_argument("--write", action="store_true", help="write the outputs instead of comparing")
    parser.add_argument("--repo", default=str(ROOT))
    args = parser.parse_args(argv)
    try:
        generated = outputs(args.repo)
    except (OSError, ValueError, KeyError, TypeError, AssertionError) as exc:
        print("ERROR USAGE gen_api_types: %s" % exc.__class__.__name__)
        return 2
    drift = []
    for rel, text in generated.items():
        path = Path(args.repo) / rel
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
        elif not path.is_file() or path.read_text(encoding="utf-8") != text:
            drift.append(rel)
    if drift:
        for rel in drift:
            print("ERROR GENERATED_DRIFT %s: differs from the generator output (run: python3 tools/gen_api_types.py --write)" % rel)
        return 1
    print("OK gen_api_types: %s" % ("written" if args.write else "generated files are current"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
