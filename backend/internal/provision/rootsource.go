// ErrVolumeSource means a qualification disk's filesystem path is not provably the file of the libvirt volume created for this VM
// (CT-PRODUCT-DELIVERY-009 for the root overlay, its addendum for the NoCloud seed). The reason is deliberately not included.
var ErrVolumeSource = errors.New("provision: volume source refused")

// VolumeSource is the resolved filesystem location of one libvirt volume Svavyom created for a VM: the volume's own name, the path
// libvirt reports for it and the target directory of the configured pool. The domain names the volume as a file source at Path, so
// the per-guest AppArmor profile libvirt generates names exactly that file; the volume itself is still created, identified and
// deleted through the storage-pool API.
type VolumeSource struct {
	Name     string // the logical libvirt volume name (RootVolumeName / SeedVolumeName)
	Path     string // "<pool target>/<Name>"
	PoolPath string // the configured pool's target directory
}

// RootSource is the resolved placement of the writable root overlay.
type RootSource = VolumeSource

// DiskSources are the resolved sources of the two disks Svavyom defines for a VM.
type DiskSources struct {
	Root, Seed VolumeSource
}

// ResolveVolumeSource turns libvirt's answer about a volume into the one path the domain may name. It requires: an absolute, clean
// path of the closed alphabet, equal to the pool target joined with the expected volume name derived from the creation UUID (so it
// is inside the configured pool and is this volume, not a lookalike); the volume name libvirt returned to be that same name; and,
// from the host's own inspection of that path, a regular file that is not a symlink and has no symlink in any ancestor. A path
// nobody could inspect is refused, never assumed.
func ResolveVolumeSource(want string, v VolumeInfo) (VolumeSource, error) {
	r := VolumeSource{Name: v.Name, Path: v.Path, PoolPath: v.PoolPath}
	if want == "" || v.Name != want {
		return VolumeSource{}, ErrVolumeSource
	}
	if err := r.validateAs(want); err != nil {
		return VolumeSource{}, err
	}
	if !v.FSChecked || !v.Regular || v.Symlink || !v.Canonical {
		return VolumeSource{}, ErrVolumeSource
	}
	return r, nil
}

// ResolveRootSource resolves the root overlay of s.
func ResolveRootSource(s Spec, v VolumeInfo) (VolumeSource, error) {
	return ResolveVolumeSource(RootVolumeName(s.UUID), v)
}

// ResolveSeedSource resolves the NoCloud seed volume of s.
func ResolveSeedSource(s Spec, v VolumeInfo) (VolumeSource, error) {
	return ResolveVolumeSource(SeedVolumeName(s.UUID), v)
}

func (r VolumeSource) validateAs(want string) error {
	ok := func(p string) bool {
		return backingPathRE.MatchString(p) && filepath.Clean(p) == p && filepath.IsAbs(p)
	}
	if want == "" || r.Name != want || !ok(r.Path) || !ok(r.PoolPath) || r.PoolPath == "/" || r.Path != filepath.Join(r.PoolPath, want) {
		return ErrVolumeSource
	}
	return nil
}

func (d DiskSources) validateFor(s Spec) error {
	// Both disks must be this VM's own pair: the same revision (the disks a create made have none), the right role, the VM's UUID.
	ru, rr, rrev, rok := ParseVolumeName(d.Root.Name)
	su, sr, srev, sok := ParseVolumeName(d.Seed.Name)
	if !rok || !sok || ru != s.UUID || su != s.UUID || rr != "root" || sr != "seed" || rrev != srev {
		return ErrVolumeSource
	}
	if err := d.Root.validateAs(d.Root.Name); err != nil {
		return err
	}
	if err := d.Seed.validateAs(d.Seed.Name); err != nil {
		return err
	}
	if d.Root.Path == d.Seed.Path {
		return ErrVolumeSource
	}
	return nil
}

type sourceDiskDoc struct {
	Type   string `xml:"type,attr"`
	Device string `xml:"device,attr"`
	Driver struct {
		Type string `xml:"type,attr"`
	} `xml:"driver"`
	Source struct {
		File      string        `xml:"file,attr"`
		Pool      string        `xml:"pool,attr"`
		Volume    string        `xml:"volume,attr"`
		Seclabels []seclabelDoc `xml:"seclabel"`
	} `xml:"source"`
	ReadOnly *struct{} `xml:"readonly"`
}

// seedFormat is the NoCloud seed's media format (the driver type the seed has always had).
const seedFormat = "raw"

// CheckDomainSources inspects a domain definition, generated by DomainXML or read back from libvirt, and requires both qualification
// disks to be file-backed at exactly the validated resolved paths and never a pool/volume reference:
//
//   - exactly one disk of device 'disk': type=file, source file exactly s.Root.Path;
//   - exactly one disk of device 'cdrom': type=file, driver raw, source file exactly s.Seed.Path, readonly;
//   - no disk of any other device, and no pool/volume attribute on either source;
//   - no no-relabel directive on either of these sources (the only one in a domain belongs to the immutable backing image, which
//     CheckDomainBacking verifies).
func CheckDomainSources(x string, s DiskSources) error {
	if err := CheckDomainRootSource(x, s.Root); err != nil {
		return err
	}
	return CheckDomainSeedSource(x, s.Seed)
}

// CheckDomainRootSource is the root half of CheckDomainSources (the document must still contain no other kind of disk).
func CheckDomainRootSource(x string, root VolumeSource) error {
	return checkDomainDisk(x, "disk", root.Path)
}

// CheckDomainSeedSource is the seed half of CheckDomainSources.
func CheckDomainSeedSource(x string, seed VolumeSource) error {
	return checkDomainDisk(x, "cdrom", seed.Path)
}

// checkDomainDisk requires the document to hold exactly one disk of the given device, no disk of any other device, and no pool/volume
// source or no-relabel directive on any disk; that one disk must be the file at path (and, for the seed, a readonly raw cdrom).
func checkDomainDisk(x, device, path string) error {
	var d struct {
		Disks []sourceDiskDoc `xml:"devices>disk"`
	}
	if len(x) > 1<<20 || xml.Unmarshal([]byte(x), &d) != nil || path == "" {
		return ErrVolumeSource
	}
	n := 0
	for _, disk := range d.Disks {
		if isISODisk(disk) {
			continue // installation media (DR-023 D3; attached later with iso_attach or rescue, DR-026): a read-only CD with the one source directive that keeps its store file's owner unchanged. It is neither the root disk nor the seed.
		}
		if disk.Source.Pool != "" || disk.Source.Volume != "" || relabelOff(disk.Source.Seclabels) {
			return ErrVolumeSource
		}
		if disk.Device != "disk" && disk.Device != "cdrom" {
			return ErrVolumeSource
		}
		if disk.Device != device {
			continue
		}
		if device == "disk" && disk.Source.File != path && isDataDisk(disk) {
			continue // an attached standalone data volume (DR-023 D2) is not the root
		}
		n++
		if disk.Type != "file" || disk.Source.File != path {
			return ErrVolumeSource
		}
		if device == "cdrom" && (disk.Driver.Type != seedFormat || disk.ReadOnly == nil) {
			return ErrVolumeSource
		}
	}
	if n != 1 {
		return ErrVolumeSource
	}
	return nil
}

// isDataDisk reports whether a disk of the definition is a Svavyom data volume: a qcow2 file at a clean absolute path in the closed alphabet whose last
// element is a data volume name. Whether it is attached on purpose is the attach operation's business; this only recognises Svavyom's own.
func isDataDisk(d sourceDiskDoc) bool {
	f := d.Source.File
	if d.Device != "disk" || d.Type != "file" || d.Driver.Type != "qcow2" || !backingPathRE.MatchString(f) || filepath.Clean(f) != f {
		return false
	}
	_, ok := ParseDataVolumeName(filepath.Base(f))
	return ok
}

// DataDiskXML renders the device element attaching a data volume. The path is the resolved file of the volume (ResolveVolumeSource), the
// device one of vdb to vdz; the user alias repeats the ownership marker so the definition itself names the volume.
func DataDiskXML(volume string, src VolumeSource, dev string) (string, error) {
	if !ValidDataName(volume) || !dataDevRE.MatchString(dev) || src.validateAs(DataVolumeName(volume)) != nil {
		return "", ErrVolumeSource
	}
	return "<disk type='file' device='disk'><driver name='qemu' type='qcow2'/><source file='" + src.Path + "'/><target dev='" + dev + "' bus='virtio'/>" +
		"<alias name='ua-svavyom-vol-" + volume + "'/></disk>", nil
}

var dataDevRE = regexp.MustCompile(`^vd[b-z]$`)

// DataDiskPath returns the file of the data volume's disk in a domain definition (ok is false when the definition carries no such disk).
func DataDiskPath(x, volume string) (string, bool) {
	var d struct {
		Disks []sourceDiskDoc `xml:"devices>disk"`
	}
	if len(x) > 1<<20 || xml.Unmarshal([]byte(x), &d) != nil || !ValidDataName(volume) {
		return "", false
	}
	for _, disk := range d.Disks {
		if isDataDisk(disk) && filepath.Base(disk.Source.File) == DataVolumeName(volume) {
			return disk.Source.File, true
		}
	}
	return "", false
}
