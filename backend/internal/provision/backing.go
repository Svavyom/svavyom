package provision

import (
	"encoding/xml"
	"errors"
	"path/filepath"
	"regexp"
)

// ErrBacking means a domain's backing-image declaration is not exactly the one the catalog qualifies (CT-PRODUCT-DELIVERY-008).
// The reason is deliberately not included.
var ErrBacking = errors.New("provision: backing image declaration refused")

// BackingFormat is the only format a managed base image is declared with.
const BackingFormat = "qcow2"

// backingPathRE is the closed path alphabet of a declared backing source: absolute, no quote, markup, space or control character.
var backingPathRE = regexp.MustCompile(`^/[A-Za-z0-9._/-]{1,198}$`)

// BackingImage is the immutable base image a VM's root overlay is declared against. It is produced by Catalog.Backing (which
// verifies trust and digest) and checked again, field by field, when the domain XML is rendered. The domain XML names it
// explicitly instead of relying on the backing-file metadata embedded in the overlay.
type BackingImage struct {
	Path   string // "<catalog_dir>/store/<sha256>.qcow2"
	Format string // qcow2
	SHA256 string
}

// Backing verifies the catalog image (trust policy, size, SHA-256: see Verify) and returns its explicit backing declaration. The
// path must also be canonical, with no symlink anywhere in it: AppArmor and libvirt act on resolved paths, so a declared path
// that is not the real path would not describe what QEMU opens.
func (c *Catalog) Backing(im Image) (BackingImage, error) {
	p, err := c.Verify(im)
	if err != nil {
		return BackingImage{}, err
	}
	if real, err := filepath.EvalSymlinks(p); err != nil || real != p {
		return BackingImage{}, ErrImageChanged
	}
	return BackingImage{Path: p, Format: im.Format, SHA256: im.SHA256}, nil
}

// validateFor requires b to be exactly the catalog-qualified managed image of s under cfg: the store path derived from the
// configured catalog directory and the spec's recorded digest, the qcow2 format, and a path made only of safe characters.
func (b BackingImage) validateFor(cfg Config, s Spec) error {
	want := filepath.Join(cfg.CatalogDir, StoreDir, s.ImageSHA256+".qcow2")
	if b.Path != want || filepath.Clean(b.Path) != b.Path || !backingPathRE.MatchString(b.Path) || b.Format != BackingFormat || b.SHA256 != s.ImageSHA256 {
		return ErrBacking
	}
	return nil
}

type seclabelDoc struct {
	Model   string `xml:"model,attr"`
	Type    string `xml:"type,attr"`
	Relabel string `xml:"relabel,attr"`
}

type sourceDoc struct {
	Pool      string        `xml:"pool,attr"`
	Volume    string        `xml:"volume,attr"`
	File      string        `xml:"file,attr"`
	Seclabels []seclabelDoc `xml:"seclabel"`
}

type backingDoc struct {
	Type   string `xml:"type,attr"`
	Format struct {
		Type string `xml:"type,attr"`
	} `xml:"format"`
	Source sourceDoc   `xml:"source"`
	Next   *backingDoc `xml:"backingStore"`
}

type diskCheckDoc struct {
	Device string `xml:"device,attr"`
	Driver struct {
		Type string `xml:"type,attr"`
	} `xml:"driver"`
	Source  sourceDoc   `xml:"source"`
	Backing *backingDoc `xml:"backingStore"`
}

type securityCheckDoc struct {
	Seclabels []seclabelDoc  `xml:"seclabel"`
	Disks     []diskCheckDoc `xml:"devices>disk"`
}

// CheckDomainBacking inspects a domain definition (generated by DomainXML, or read back from libvirt) and requires, for the
// root disk, exactly the security shape of CT-PRODUCT-DELIVERY-008:
//
//   - an explicit backingStore of type file, format qcow2, whose source is exactly b.Path, followed by an empty terminating
//     backingStore;
//   - on that backing source (and only there) <seclabel model='dac' relabel='no'/>, so libvirt's DAC driver never chowns the
//     immutable base image;
//   - nothing that disables DAC handling for the writable overlay or the seed volume;
//   - no domain-wide seclabel that turns confinement or relabelling off (model none, or DAC relabel='no').
func CheckDomainBacking(x string, b BackingImage) error {
	var d securityCheckDoc
	if len(x) > 1<<20 || xml.Unmarshal([]byte(x), &d) != nil {
		return ErrBacking
	}
	for _, sl := range d.Seclabels {
		if sl.Model == "none" || sl.Type == "none" || sl.Relabel == "no" {
			return ErrBacking
		}
	}
	roots := 0
	for _, disk := range d.Disks {
		if disk.Device == "cdrom" {
			if disk.Backing != nil && disk.Backing.Source.File != "" || relabelOff(disk.Source.Seclabels) {
				return ErrBacking
			}
			continue
		}
		roots++
		if relabelOff(disk.Source.Seclabels) || disk.Driver.Type != BackingFormat { // the writable overlay keeps the default DAC handling
			return ErrBacking
		}
		bs := disk.Backing
		if bs == nil || bs.Type != "file" || bs.Format.Type != BackingFormat || bs.Source.File != b.Path || b.Path == "" || b.Format != BackingFormat {
			return ErrBacking
		}
		if len(bs.Source.Seclabels) != 1 || bs.Source.Seclabels[0].Model != "dac" || bs.Source.Seclabels[0].Relabel != "no" {
			return ErrBacking
		}
		if end := bs.Next; end == nil || end.Type != "" || end.Format.Type != "" || end.Source.File != "" || len(end.Source.Seclabels) != 0 || end.Next != nil {
			return ErrBacking
		}
	}
	if roots != 1 {
		return ErrBacking
	}
	return nil
}

func relabelOff(sl []seclabelDoc) bool {
	for _, s := range sl {
		if s.Relabel == "no" {
			return true
		}
	}
	return false
}
