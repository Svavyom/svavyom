func TestNetworkOperationReplayAndConflict(t *testing.T) {
	e, _ := newNet(t)
	a := mustSubmit(t, e.m, netReq(NetworkCreate, KindNetwork, "lab-net", "same", labParams))
	b := mustSubmit(t, e.m, netReq(NetworkCreate, KindNetwork, "lab-net", "same", labParams))
	if a.ID != b.ID || a.Params.NewUUID != b.Params.NewUUID {
		t.Fatalf("a replay must return the same operation: %+v %+v", a, b)
	}
	other := labParams
	other.DHCPEnd = "10.77.0.100"
	if _, err := e.m.Submit(alice, netReq(NetworkCreate, KindNetwork, "lab-net", "same", other)); CategoryOf(err) != CatConflict {
		t.Fatalf("the same key with other inputs: %v", err)
	}
}

func TestNetworkUnknownOutcomeIsRetriedNotGuessed(t *testing.T) {
	e, h := newNet(t)
	h.err = timeoutErr("net")
	op := mustSubmit(t, e.m, netReq(NetworkCreate, KindNetwork, "lab-net", "k1", labParams))
	got, err := e.m.Run(context.Background(), op.ID)
	if err != nil || got.Status != Running || got.ErrorCategory != CatTimeout {
		t.Fatalf("%+v %v", got, err)
	}
	rec, err := e.m.ReconcileOne(context.Background(), op.ID)
	if err != nil || rec.Status != RetryableFailure || !rec.UnknownOutcome {
		t.Fatalf("%+v %v", rec, err)
	}
	h.err = nil // the retry runs the idempotent operation again and finishes it
	mustRun(t, e.m, op.ID, Succeeded)
}

