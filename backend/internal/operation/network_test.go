// netHost records the M3 calls; err decides what each one reports.
type netHost struct {
	hypervisor.Hypervisor
	mu    sync.Mutex
	calls []string
	got   Params
	err   error
}

func (h *netHost) rec(s string) error {
	h.mu.Lock()
	defer h.mu.Unlock()
	h.calls = append(h.calls, s)
	return h.err
}
func (h *netHost) NetworkCreate(_ context.Context, n string, p Params) error {
	h.got = p
	return h.rec("create " + n)
}
func (h *netHost) NetworkStart(_ context.Context, n string) error { return h.rec("start " + n) }
func (h *netHost) NetworkStop(_ context.Context, n string) error  { return h.rec("stop " + n) }
func (h *netHost) NetworkAutostart(_ context.Context, n string, on bool) error {
	if on {
		return h.rec("autostart-on " + n)
	}
	return h.rec("autostart-off " + n)
}
func (h *netHost) NetworkDelete(_ context.Context, n string) error { return h.rec("delete " + n) }
func (h *netHost) Compute(_ context.Context, v string, c, m int) error {
	h.got = Params{VCPUs: c, MemoryMiB: m}
	return h.rec("compute " + v)
}
func (h *netHost) ReserveIP(_ context.Context, v, ip string) error {
	return h.rec("reserve " + v + " " + ip)
}
func (h *netHost) ReleaseIP(_ context.Context, v string) error { return h.rec("release " + v) }

func netReq(t Type, kind, id, key string, p Params) Request {
	return Request{ProjectID: "p1", Type: t, Kind: kind, ResourceID: id, IdempotencyKey: key, Params: p}
}

func newNet(t *testing.T) (*env, *netHost) {
	t.Helper()
	e := newEnv(t)
	h := &netHost{Hypervisor: fake.New()}
	e.m = e.manager(h)
	return e, h
}

var labParams = Params{Subnet: "10.77.0.0/24", DHCPStart: "10.77.0.10", DHCPEnd: "10.77.0.200"}

func TestNetworkOperationsRunWithTheirTypedParameters(t *testing.T) {
	e, h := newNet(t)
	ctx := context.Background()
	cases := []struct {
		req  Request
		call string
	}{
		{netReq(NetworkCreate, KindNetwork, "lab-net", "k1", labParams), "create lab-net"},
		{netReq(NetworkStart, KindNetwork, "lab-net", "k2", Params{}), "start lab-net"},
		{netReq(NetworkStop, KindNetwork, "lab-net", "k3", Params{}), "stop lab-net"},
		{netReq(NetworkAutostart, KindNetwork, "lab-net", "k4", Params{Autostart: "on"}), "autostart-on lab-net"},
		{netReq(NetworkAutostart, KindNetwork, "lab-net", "k5", Params{Autostart: "off"}), "autostart-off lab-net"},
		{netReq(NetworkDelete, KindNetwork, "lab-net", "k6", Params{}), "delete lab-net"},
		{netReq(Compute, KindVM, "vm-a", "k7", Params{VCPUs: 4, MemoryMiB: 2048}), "compute vm-a"},
		{netReq(ReserveIP, KindVM, "vm-a", "k8", Params{IPAddress: "10.77.0.50"}), "reserve vm-a 10.77.0.50"},
		{netReq(ReleaseIP, KindVM, "vm-a", "k9", Params{}), "release vm-a"},
	}
	for _, c := range cases {
		op := mustSubmit(t, e.m, c.req)
		mustRun(t, e.m, op.ID, Succeeded)
		if last := h.calls[len(h.calls)-1]; last != c.call {
			t.Errorf("%s: host saw %q, want %q", c.req.Type, last, c.call)
		}
	}
	// the network UUID is generated by the server and reaches the host with the typed inputs
	op := mustSubmit(t, e.m, netReq(NetworkCreate, KindNetwork, "second", "k10", labParams))
	if op.Params.NewUUID == "" {
		t.Fatalf("%+v", op.Params)
	}
	_ = ctx
}

